"""Seal the final local review pack and verify historical qualitative provenance."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT.parent


def sha(path):
    with Path(path).open("rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def main(out):
    out.mkdir(parents=True, exist_ok=False)
    checked = {}
    for path in [BASE / "research-paper-v10-judges/provenance.json",
                 ROOT / "reports/v10_qualitative_judges_20261116/figure_values.json",
                 ROOT / "reports/v11_submission_20261116_02/inputs.json"]:
        data = json.loads(path.read_text(encoding="utf-8"))
        for name, digest in data.get("inputs", data).items():
            candidate = BASE / name
            assert sha(candidate) == digest, name
            checked[candidate.relative_to(BASE).as_posix()] = digest
    # The historical robust-judge headline CI is retained explicitly.
    with (ROOT / "reports/v2_quickwins/regrade/regrade_summary.csv").open(encoding="utf-8-sig", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["set"] == "diffusion_fs_t100_w5"
                and r["judge_seed"] == "0" and r["subset"] == "all"]
    assert len(rows) == 1
    robust = {k: float(rows[0][k]) for k in ["hit", "hit_patient_lo", "hit_patient_hi"]}
    assert robust == {"hit": .07, "hit_patient_lo": .010416666666666666, "hit_patient_hi": .15}
    # Freeze all transitive candidates selected by the actual pip dry-run.
    env_report = ROOT / "reports/v11_environment_resolution_20261116_01"
    resolver = json.loads((env_report / "resolver.json").read_text(encoding="utf-8"))
    pins = sorted((item["metadata"]["name"], item["metadata"]["version"],
                   item["download_info"]["archive_info"]["hashes"]["sha256"]) for item in resolver["install"])
    lock = env_report / "requirements-resolved.txt"
    with lock.open("x", encoding="utf-8") as f:
        f.write("# Windows/Python 3.12 resolver-only candidate; tensor packages excluded; not installation validation.\n--require-hashes\n")
        for name, version, digest in pins:
            f.write(f"{name}=={version} --hash=sha256:{digest}\n")
    (env_report / "README.md").write_text(
        "# Candidate dependency resolution (no installation)\n\n"
        "Produced by a captured `python -m pip install --dry-run --ignore-installed --only-binary=:all: "
        "--report reports/v11_environment_resolution_20261116_01/resolver.json "
        "-r environment/requirements-evaluation-candidate.txt` invocation.\n\n"
        "`resolver.json`: complete wheel/metadata resolution; `resolver-log.txt`: stdout/stderr; "
        "`status.json`: exit status and explicit no-install/no-tensor scope.\n"
        "`requirements-resolved.txt`: exact transitive pins and wheel SHA-256, sealed from that report by "
        "`scripts/v11_submission/seal_handoff.py`. Tensor requirements are separate.\n"
        "This resolves the proposed dependency constraints; it does not validate a fresh installation, "
        "GPU inference, metric parity or long-term wheel availability. No large tensor wheels were downloaded.\n",
        encoding="utf-8")
    release = {}
    for folder in [BASE / "research-paper-v11-evaluation", ROOT / "scripts/v11_submission", ROOT / "environment"]:
        for path in folder.rglob("*"):
            if path.is_file() and "__pycache__" not in path.parts and "qa" not in path.parts and path.suffix != ".log":
                release[path.relative_to(BASE).as_posix()] = sha(path)
    for path in [ROOT / "README.md", ROOT / "REPRODUCIBILITY.md", ROOT / "api/publication.py",
                 ROOT / "api/main.py", ROOT / "api/package_demo.py", lock]:
        release[path.relative_to(BASE).as_posix()] = sha(path)
    result = dict(historical_provenance_files=len(checked), historical_inputs_unchanged=True,
                  historical_robust_judge0=robust, resolved_candidate_packages=len(pins),
                  figures_tables_frozen=True, pdf_visual_review="All sixteen pages inspected via four contact sheets; no clipping or overlap seen. Final reference-only page is retained in this uncompressed supervisor master.",
                  known_compiler_warnings="Existing font configuration/algorithm.sty encoding and underfull boxes; no missing output glyphs or overfull boxes.",
                  no_model_training=True, no_external_contact=True, no_submission=True,
                  clean_install_validated=False, supervisor_approval=False)
    for name, value in [("historical-inputs.json", checked), ("release-files.json", release), ("review.json", result)]:
        with (out / name).open("x", encoding="utf-8") as f:
            json.dump(value, f, indent=2)
    (out / "README.md").write_text(
        "# Final v11 local handoff seal\n\nGenerated by `scripts/v11_submission/seal_handoff.py`.\n\n"
        "`historical-inputs.json`: original v10 figure provenance and v11 scientific/model inputs rechecked unchanged.\n"
        "`release-files.json`: hashes of the new master, source, guides and changed API code.\n"
        "`review.json`: visual review, exact historical robust-judge CI, environment-resolution scope and remaining human/install checks.\n"
        "The environment lock was sealed from the actual pip resolver report, without installation.\n"
        "Earlier `_01`/`_02` handoff and release checks remain preserved as separate receipts.\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    main(parser.parse_args().output.resolve())
