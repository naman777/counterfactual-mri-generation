"""Check v11 PDF, preserved figures, API paper bytes, saved replay and demo plan."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT.parent
sys.path.insert(0, str(ROOT))
PAPER = BASE / "research-paper-v11-evaluation"


def main(out):
    import fitz
    from PIL import Image, ImageDraw
    from fastapi.testclient import TestClient
    from api.main import app
    from api.publication import PAPER_PATH, PAPER_RELATIVE_PATH, PAPER_DOWNLOAD_NAME
    from api.package_demo import collect_files

    out.mkdir(parents=True, exist_ok=False)
    qa = PAPER / "qa"
    qa.mkdir(exist_ok=False)
    document = fitz.open(PAPER_PATH)
    combined = "\n".join(p.get_text() for p in document)
    assert "??" not in combined and "\ufffd" not in combined
    assert "7% (1" in combined.replace("\n", " ") or "7%" in combined
    log = (PAPER / "paper_v11_ieee.log").read_text(encoding="utf-8", errors="replace")
    fatal = [line for line in log.splitlines() if "Overfull" in line or "Missing character:" in line
             or ("undefined" in line.lower() and "Font shape" not in line)]
    assert not fatal, fatal
    for index, page in enumerate(document):
        assert len(page.get_text().strip()) > 100
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                for span in line["spans"]:
                    box = fitz.Rect(span["bbox"])
                    assert box.x0 >= -.1 and box.x1 <= page.rect.width + .1, (index, span["text"])
                    assert box.y0 >= -.1 and box.y1 <= page.rect.height + .1, (index, span["text"])
        page.get_pixmap(dpi=110, alpha=False).save(qa / f"page_{index+1:02}.png")
    sheets = []
    for start in range(0, len(document), 4):
        sheet = Image.new("RGB", (1320, 1770), "#e9edf1")
        draw = ImageDraw.Draw(sheet)
        for offset, index in enumerate(range(start, min(start+4, len(document)))):
            with Image.open(qa / f"page_{index+1:02}.png") as image:
                image.thumbnail((640, 840))
                x, y = (offset % 2) * 660 + 10, (offset // 2) * 885 + 30
                sheet.paste(image, (x, y))
                draw.text((x, y-20), f"Page {index+1}", fill="black")
        target = qa / f"contact_{start//4+1:02}.png"
        sheet.save(target)
        sheets.append(str(target))
    with TestClient(app) as client:
        response = client.get("/paper")
        assert response.status_code == 200
        assert response.content == PAPER_PATH.read_bytes()
        assert PAPER_DOWNLOAD_NAME in response.headers["content-disposition"]
    files = collect_files()
    assert all(p.is_file() for p in files)
    assert ROOT / "api/publication.py" in files
    # All tests use saved outputs/CPU classification; no diffusion training or cloud app.
    run = subprocess.run([sys.executable, "-m", "unittest", "api.test_contract", "api.test_dashboard_fixes", "-v"],
                         cwd=ROOT, text=True, capture_output=True, env={**os.environ, "MRONE_DEMO_ONLY": "0"})
    (out / "api-tests.txt").write_text(run.stdout + run.stderr, encoding="utf-8")
    assert run.returncode == 0, (run.stdout + run.stderr)[-5000:]
    manifest = subprocess.run([sys.executable, "-m", "api.package_demo", "--manifest-only", "--output", str(out / "demo-plan.json")],
                              cwd=ROOT, text=True, capture_output=True)
    (out / "package-check.txt").write_text(manifest.stdout + manifest.stderr, encoding="utf-8")
    assert manifest.returncode == 0, manifest.stderr
    plan = json.loads((out / "demo-plan.json").read_text())
    assert PAPER_RELATIVE_PATH.as_posix() in plan["files"]
    assert not any(p.startswith("research-paper-v5/") for p in plan["files"])
    result = dict(pdf_pages=len(document), overfull_or_missing_or_unresolved=[], page_bounds_pass=True,
                  paper_endpoint_bytes_match=True, paper_download_name=PAPER_DOWNLOAD_NAME,
                  demo_plan_includes_current_paper=True, demo_entries=len(plan["files"]),
                  api_test_summary=re.findall(r"Ran \d+ tests.*", run.stderr), api_tests_pass=True,
                  rendered_contact_sheets=sheets, visual_review_required=True,
                  paper_sha256=hashlib.sha256(PAPER_PATH.read_bytes()).hexdigest(),
                  archive_written=False, clean_install_validated=False)
    with (out / "verification.json").open("x", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
    (out / "README.md").write_text(
        "# v11 PDF/API verification\n\nGenerated by `scripts/v11_submission/verify_release.py`.\n\n"
        "`verification.json`: PDF text/bounds, API byte identity, packaging plan and fresh API/replay tests.\n"
        "`api-tests.txt`: complete test output, including dependency warnings.\n"
        "`demo-plan.json`, `package-check.txt`: exact checked archive entries, without copying large arrays.\n"
        "Rendered pages/contact sheets live in `research-paper-v11-evaluation/qa/`; visual inspection is separate.\n"
        "No training, large download, external communication, archive transfer or clean installation was performed.\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    main(parser.parse_args().output.resolve())
