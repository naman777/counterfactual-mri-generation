"""Check completed pilot provenance, paired controls, review IDs and no false validation."""
import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
from scripts.v4_convergence.core import digest, json_write
from scripts.v5_anatomy.csv_io import read_table

ROOT=Path(__file__).resolve().parents[2]


def verify(pilot,output,code_snapshot=None):
    pilot,output=Path(pilot).resolve(),Path(output).resolve()
    protocol=json.loads((pilot/'protocol.json').read_text())
    complete=json.loads((pilot/'complete.json').read_text())
    inputs=json.loads((pilot/'inputs.json').read_text())
    assert complete['complete'] and complete['split']=='val'
    archived_code=[]
    for path,expected in inputs.items():
        if digest(ROOT/path)==expected:
            continue
        if code_snapshot and Path(path).as_posix().startswith('scripts/v5_anatomy/'):
            archived=Path(code_snapshot)/Path(path).name
            assert digest(archived)==expected,path
            archived_code.append(dict(path=path,archive=str(archived.resolve()),sha256=expected))
        else:
            raise AssertionError(path)
    generation=read_table(pilot/'generation.csv')
    predictions=read_table(pilot/'predictions.csv')
    selection=read_table(pilot/'selection.csv')
    assert len(selection)==selection.patient_id.nunique()==protocol['patients']
    assert not generation.review_id.duplicated().any()
    assert not generation.anatomy_validated.any()
    assert generation.human_preservation_pass.isna().all()
    assert predictions.target_hit_and_human_preservation.isna().all()
    assert np.array_equal(generation.source_echo,generation.target_echo)
    assert set(predictions.judge)=={'original_predictor',*[f'heldout_orientation_robust{i}' for i in range(3)]}
    variants={'identity','null','sdedit',*[f'anchor_{s:g}' for s in protocol['anchor_strengths']]}
    assert set(generation.variant)==variants
    output_hashes={name:digest(pilot/name) for name in ['protocol.json','inputs.json','selection.csv',
                   'generation.csv','predictions.csv','summary.csv','paired_differences.csv','complete.json']}
    for case,group in generation.groupby('case_id'):
        assert set(group.variant)==variants
        assert group.seed.nunique()==1 and group.timestep.nunique()==1 and group.guidance.nunique()==1
        with np.load(pilot/'arrays'/f'{case}.npz') as arrays:
            np.testing.assert_array_equal(arrays['identity'],arrays['source'])
            source_path=ROOT/str(group.iloc[0].source_path).replace('\\','/')
            np.testing.assert_array_equal(arrays['source'],np.load(source_path).astype(np.float32))
            for key in arrays.files:
                assert arrays[key].shape==(128,128)
                assert np.isfinite(arrays[key]).all() and arrays[key].min()>=0 and arrays[key].max()<=1
        output_hashes[f'arrays/{case}.npz']=digest(pilot/'arrays'/f'{case}.npz')
        for _,row in group.iterrows():
            assert row.source_mfg==row.target_mfg if row.axis=='field_strength' else row.source_fs==row.target_fs
            assert row.source_fs!=row.target_fs if row.axis=='field_strength' else row.source_mfg!=row.target_mfg
    mapping=read_table(pilot/'review/private_mapping.csv')
    review=read_table(pilot/'review/review_template.csv')
    assert set(mapping.review_id)==set(generation.review_id)==set(review.review_id)
    assert review.anatomy_preserved.isna().all() and review.reviewer.isna().all()
    summary=read_table(pilot/'summary.csv')
    assert not summary.anatomy_validated.any()
    assert len(predictions)==len(generation)*4==complete['judge_rows']
    assert len(generation)==complete['output_images']
    # Verify binary joint proxy result against its actual constituent labels.
    np.testing.assert_array_equal(predictions.target_hit_and_proxy_screen,
                                  predictions.target_hit.astype(bool)&predictions.proxy_screen_pass.astype(bool))
    output.mkdir(parents=True,exist_ok=False)
    json_write(output/'output_hashes.json',output_hashes)
    json_write(output/'verification.json',dict(pilot=str(pilot),patients=len(selection),
        requests=generation.case_id.nunique(),images=len(generation),judge_rows=len(predictions),
        input_hashes_verified=len(inputs),paired_seeds_settings=True,identity_arrays_unchanged=True,
        echo_fixed=True,validation_only=True,human_labels_not_invented=True,all_three_judges=True,
        frozen_data_and_models_unchanged=True,archived_run_code=archived_code,clinical_validation=False))
    (output/'README.md').write_text('Generated by scripts/v5_anatomy/verify_pilot.py.\n'
        'verification.json checks immutable input hashes, validation cohort, paired controls, fixed EchoTime,\n'
        'source/identity arrays, predictions, blinded-review IDs and missing human preservation labels.\n'
        'output_hashes.json fingerprints completed pilot tables, metadata and arrays.\n'
        'This is software/protocol verification, not anatomical or clinical validation.\n',encoding='utf-8')
    return output


if __name__=='__main__':
    p=argparse.ArgumentParser(__doc__);p.add_argument('--pilot',required=True);p.add_argument('--output',required=True)
    p.add_argument('--code-snapshot')
    args=p.parse_args();print(verify(args.pilot,args.output,args.code_snapshot))
