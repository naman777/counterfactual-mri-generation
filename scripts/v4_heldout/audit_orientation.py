"""Read-only orientation audit prompted by held-out cohort visual QA.

python -m scripts.v4_heldout.audit_orientation --plan-run preflight_20261016_01 --run-id orientation_20261016_01
Reads headers for retained slices; never rewrites images or runs a model.
"""
import argparse
import json

import numpy as np
import pandas as pd
import pydicom

from .audit import ROOT, sha
from .download import valid_id


def main(plan_run, run_id):
    valid_id(plan_run)
    valid_id(run_id)
    paths = [ROOT / f'data/processed/ax_t1_128/splits/{split}.csv' for split in ['train', 'val', 'test']]
    old = pd.concat([pd.read_csv(path).assign(cohort='original', split=path.stem) for path in paths])
    new_path = ROOT / 'data/processed/ax_t1_128_heldout' / plan_run / 'processed_metadata.csv'
    new = pd.read_csv(new_path).assign(cohort='heldout')
    new['split'] = new.judge_split
    out = ROOT / 'reports/v4_heldout_judge' / run_id
    out.mkdir(parents=True, exist_ok=False)
    rows = []
    for i, (_, row) in enumerate(pd.concat([old, new], ignore_index=True).iterrows()):
        ds = pydicom.dcmread(row.slice_path, stop_before_pixels=True)
        vector = np.asarray(getattr(ds, 'ImageOrientationPatient', []), dtype=float)
        present = len(vector) == 6 and np.isfinite(vector).all()
        column_y = float(vector[4]) if present else float('nan')
        sign = 'positive' if column_y > 0.5 else ('negative' if column_y < -0.5 else 'other_or_missing')
        rows.append({'cohort': row.cohort, 'split': row.split, 'patient_id': row.patient_id, 'sop_uid': str(ds.SOPInstanceUID), 'series_uid': str(ds.SeriesInstanceUID), 'manufacturer_label': int(row.manufacturer_label), 'field_strength_label': int(row.field_strength_label), 'iop': json.dumps(vector.tolist()), 'column_y': column_y, 'column_y_sign': sign, 'patient_position': str(getattr(ds, 'PatientPosition', '')), 'slice_path': row.slice_path})
        if (i + 1) % 2000 == 0:
            print('Audited', i + 1, 'slice headers', flush=True)
    frame = pd.DataFrame(rows)
    frame.to_csv(out / 'slice_orientation.csv', index=False)
    patient = frame.groupby(['cohort', 'split', 'patient_id', 'manufacturer_label', 'field_strength_label']).agg(slices=('sop_uid', 'size'), signs=('column_y_sign', lambda v: ' | '.join(sorted(set(v)))), patient_positions=('patient_position', lambda v: ' | '.join(sorted(set(v))))).reset_index()
    patient.to_csv(out / 'patient_orientation.csv', index=False)
    counts = frame.groupby(['cohort', 'manufacturer_label', 'column_y_sign']).agg(patients=('patient_id', 'nunique'), slices=('sop_uid', 'size')).reset_index()
    counts.to_csv(out / 'orientation_counts.csv', index=False)
    rule = np.where(frame.column_y > 0.5, 1, np.where(frame.column_y < -0.5, 0, -1))
    summary = {'exploratory_header_audit': True, 'model_evaluated': False, 'images_reoriented': False, 'original_patients': int(patient[patient.cohort.eq('original')].patient_id.nunique()), 'heldout_patients': int(patient[patient.cohort.eq('heldout')].patient_id.nunique()), 'slice_headers': len(frame), 'missing_or_non_axial_column_y': int((rule == -1).sum()), 'manufacturer_matches_column_y_sign_slices': int((rule == frame.manufacturer_label).sum()), 'patient_signs_constant': not bool(patient.signs.str.contains(' | ', regex=False).any()), 'source_sha256': sha(__file__), 'input_sha256': {str(path): sha(path) for path in paths + [new_path]}, 'dicom_standard': 'https://dicom.nema.org/medical/dicom/current/output/chtml/part03/sect_C.7.6.2.html'}
    (out / 'summary.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    (out / 'README.md').write_text('''# Exploratory orientation confound audit

Generated by `python -m scripts.v4_heldout.audit_orientation --plan-run ''' + plan_run + ''' --run-id ''' + run_id + '''`. Visual QA of the newly downloaded cohort showed opposite displayed orientation by vendor. This follow-up reads DICOM ImageOrientationPatient (0020,0037) for every retained original and new slice, without changing pixels or running a classifier.

The [DICOM Image Plane Module](https://dicom.nema.org/medical/dicom/current/output/chtml/part03/sect_C.7.6.2.html) defines the six values as row and column direction cosines in patient coordinates. The fifth value is the column-direction y component. `slice_orientation.csv` records exact vectors, positions, IDs and sign; `patient_orientation.csv` checks whether sign is constant per patient. `orientation_counts.csv` reports patients/slices by cohort, vendor and sign. `summary.json` records counts and source/input hashes. All files are made by audit_orientation.py. These descriptive counts are not an image-classifier accuracy result, clinical performance or a prespecified inferential test. The audit includes the original test headers and must be labelled exploratory.

The sign co-occurs with manufacturer in the audited arrays. Existing preprocessing rescales/clips/resizes without reorienting, so a patient-disjoint judge can still use display orientation as a vendor cue. This is a possible shortcut, not proof that a particular trained judge uses it. PatientPosition alone is insufficient because both FFP and HFP occur among Siemens images. No generator, operating point, original result or paper was changed.

Before promoting B2 manufacturer results, add a prespecified orientation stress test and an orientation-robust judge control. Options include independently sampled vertical and horizontal flips during acquisition-judge training, or DICOM-based canonical orientation applied consistently to training, validation and grading. Preserve the existing recipe as a comparison, verify physical orientation rather than blindly flipping one vendor, and report clean discrimination as well as orientation sensitivity. Do not silently transform B1's frozen data or declare old manufacturer results invalid without testing the trained models. The prepared trainer currently matches the old robust recipe (horizontal flip only); the primary-judge protocol needs this confound addressed before cloud training.
''', encoding='utf-8')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--plan-run', required=True)
    parser.add_argument('--run-id', required=True)
    args = parser.parse_args()
    main(args.plan_run, args.run_id)
