"""Post-freeze B2 accuracy and re-grading. No training or parameter selection."""
import json
import math
from pathlib import Path

import numpy as np
import pandas as pd

from scripts.v2_quickwins.judge_model import load_judge
from scripts.v4_convergence.core import digest, json_write, load_pack, probabilities
from scripts.v4_heldout.orientation_probe import intervals


def wilson(values):
    n = len(values)
    p = float(np.mean(values))
    z = 1.959963984540054
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return {'wilson_slice_lo': centre - half, 'wilson_slice_hi': centre + half}


def model_entries(base):
    base = Path(base)
    frozen = json.loads((base / 'frozen_checkpoints.json').read_text())
    if len(frozen) != 6:
        raise ValueError('Freeze all six checkpoints before accessing original test data')
    for entry in frozen:
        path = base / entry['checkpoint']
        if digest(path) != entry['sha256']:
            raise ValueError('Frozen checkpoint hash changed')
        yield entry, load_judge(path, 'cuda')


def validity(base, entry, axis):
    result = json.loads((Path(base) / entry['training_json']).read_text())
    key = 'mfg' if axis == 'manufacturer' else 'fs'
    keys = ['mfg', 'fs'] if axis == 'both' else [key]
    clean = min(result['val_clean'][f'{k}_bacc'] for k in keys)
    drop = max(result['val_clean'][f'{k}_bacc'] - result[t][f'{k}_bacc'] for k in keys for t in ['val_vertical_flip', 'val_rotate_180'])
    return bool(clean >= .8 and drop <= .05)


def test_accuracy(base, original_pack):
    base = Path(base)
    out = base / 'test_accuracy'
    out.mkdir(exist_ok=False)
    data = load_pack(original_pack, ['test'])
    x = data['test_x']
    pid = data['test_pid'].astype(str)
    assert len(x) == 934 and len(set(pid)) == 16
    noise = np.random.default_rng(0).standard_normal(x.shape, dtype=np.float32) * .03
    transforms = {'identity': x, 'noise03': np.clip(x + noise, 0, 1), 'horizontal_flip': np.flip(x, -1), 'vertical_flip': np.flip(x, -2), 'rotate_180': np.flip(x, (-2, -1))}
    rows, tables = [], []
    for entry, model in model_entries(base):
        clean = probabilities(model, x, batch=64)
        for transform, images in transforms.items():
            pred = clean if transform == 'identity' else probabilities(model, images, batch=64)
            for axis, key in [('manufacturer', 'mfg'), ('field_strength', 'fs')]:
                truth = data[f'test_{key}'].astype(int)
                correct = (pred[key].argmax(1) == truth).astype(float)
                flipped = (pred[key].argmax(1) != clean[key].argmax(1)).astype(float)
                frame = pd.DataFrame({'family': entry['family'], 'seed': entry['seed'], 'axis': axis, 'transform': transform, 'patient_id': pid, 'test_index': np.arange(len(x)), 'truth': truth, 'p0': pred[key][:, 0], 'p1': pred[key][:, 1], 'correct': correct, 'prediction_flip': flipped})
                tables.append(frame)
                for subset, mask in [('all', np.ones(len(x), bool)), ('class0', truth == 0), ('class1', truth == 1)]:
                    row = {k: frame.iloc[0][k] for k in ['family', 'seed', 'axis', 'transform']}
                    row.update(subset=subset, n=int(mask.sum()), patients=int(len(set(pid[mask]))), new_validation_validity_flag=validity(base, entry, axis))
                    for metric, values in [('accuracy', correct), ('prediction_flip', flipped)]:
                        row.update({f'{metric}_{k}': v for k, v in {**intervals(values[mask], pid[mask]), **wilson(values[mask])}.items()})
                    rows.append(row)
        print('Test accuracy complete:', entry['family'], entry['seed'], flush=True)
    pd.concat(tables, ignore_index=True).to_csv(out / 'per_slice_predictions.csv', index=False)
    pd.DataFrame(rows).to_csv(out / 'summary.csv', index=False)
    json_write(out / 'complete.json', {'complete': True, 'original_test_slices': len(x), 'original_test_patients': len(set(pid)), 'frozen_checkpoint_manifest_sha256': digest(base / 'frozen_checkpoints.json'), 'test_noise': 'numpy.default_rng(0) float32 standard normal sigma0.03, shared across judges'})
    (out / 'README.md').write_text('Generated by scripts/v4_heldout/evaluate_heldout.py:test_accuracy, after all six checkpoints are frozen. per_slice_predictions.csv gives true labels and clean/noisy/orientation-stress predictions on the original 934 slices. summary.csv reports per-head/class rates with 10,000 slice/patient bootstrap intervals, plus Wilson slice intervals to contextualise degenerate bootstrap boundaries. Descriptive new-validation validity flags never filter checkpoints or tune using test outcomes. complete.json records the frozen-manifest hash. No original test subjects participated in training/checkpoint selection.\n')
    return {'complete': True, 'output': str(out)}


def regrade(base, original_pack, stage):
    base = Path(base)
    protocol = json.loads((base / 'protocol.json').read_text())
    b1 = Path(protocol['b1_remote_root'])
    data = load_pack(original_pack, ['test'])
    pid = data['test_pid'].astype(str)
    out = base / f'regrade_{stage}'
    out.mkdir(exist_ok=False)
    inputs = []
    if stage == 'old':
        sets = json.loads((base / 'inputs/old_sets.json').read_text())
        with np.load(base / 'inputs/old_counterfactual_sets.npz', allow_pickle=False) as pack:
            for item in sets:
                idx = np.asarray(item['test_indices'], dtype=int)
                inputs.append((item['name'], item['axis'], 'cf', idx, data['test_x'][idx], pack[item['key']], {}))
        all_b3 = False
    elif stage == 'b3':
        all_b3 = (b1 / 'full/research_complete.json').exists()
        for folder in sorted((b1 / 'full/test').glob('*')):
            if not (folder / 'result.json').exists():
                continue
            job = json.loads((folder / 'job.json').read_text())
            assert job['split'] == 'test'
            with np.load(folder / 'images.npz', allow_pickle=False) as pack:
                idx = pack['indices'].astype(int)
                np.testing.assert_array_equal(pack['source_images'], data['test_x'][idx])
                for variant in pack.files:
                    if variant.startswith('source_') or variant == 'indices':
                        continue
                    inputs.append((job['name'], job['axis'], variant, idx, pack['source_images'], pack[variant], {'kind': job['kind'], 'offset': job['offset'], 't': job['t'], 'w': job['w']}))
    else:
        raise ValueError(stage)
    if not inputs:
        json_write(out / 'complete.json', {'complete': False, 'reason': 'no completed B3 test outputs', 'b1_b3_research_complete': all_b3})
        (out / 'README.md').write_text('Generated by evaluate_heldout.py:regrade. No completed B3 test output was available; see complete.json. Nothing was generated or selected here.\n')
        return {'complete': False, 'sets': 0}
    frames = []
    for entry, model in model_entries(base):
        cache = {}
        for name, axis, variant, idx, originals, images, extra in inputs:
            key = tuple(idx.tolist())
            if key not in cache:
                cache[key] = probabilities(model, originals, batch=64)
            before = cache[key]
            after = probabilities(model, images, batch=64)
            n = len(idx)
            row = {'family': entry['family'], 'seed': entry['seed'], 'set': name, 'axis': axis, 'variant': variant, 'patient_id': pid[idx], 'test_index': idx, 'example_id': [f'example_{j:03d}' for j in range(n)], 'new_validation_validity_flag': validity(base, entry, axis), **extra}
            for k in ['mfg', 'fs']:
                src = data[f'test_{k}'][idx].astype(int)
                target = 1 - src if axis == 'both' or (axis == 'manufacturer' and k == 'mfg') or (axis == 'field_strength' and k == 'fs') else src
                row[f'{k}_source'] = src
                row[f'{k}_target'] = target
                row[f'{k}_gain'] = after[k][np.arange(n), target] - before[k][np.arange(n), target]
                row[f'{k}_hit'] = (after[k].argmax(1) == target).astype(float)
                row[f'{k}_stable'] = (after[k].argmax(1) == before[k].argmax(1)).astype(float)
                row[f'{k}_source_correct'] = (before[k].argmax(1) == src).astype(float)
            frame = pd.DataFrame(row)
            if axis == 'both':
                frame['hit'] = frame.mfg_hit * frame.fs_hit
                frame['gain'] = (frame.mfg_gain + frame.fs_gain) / 2
                frame['source_correct'] = frame.mfg_source_correct * frame.fs_source_correct
                frame['direction'] = ['joint'] * n
            else:
                edited, other = ('mfg', 'fs') if axis == 'manufacturer' else ('fs', 'mfg')
                frame['hit'] = frame[f'{edited}_hit']
                frame['gain'] = frame[f'{edited}_gain']
                frame['source_correct'] = frame[f'{edited}_source_correct']
                frame['other_stability'] = frame[f'{other}_stable']
                frame['direction'] = frame[f'{edited}_source'].map({0: '0_to_1', 1: '1_to_0'})
            frames.append(frame)
        print('Regrade complete:', stage, entry['family'], entry['seed'], flush=True)
    table = pd.concat(frames, ignore_index=True)
    table.to_csv(out / 'per_slice.csv', index=False)
    summary = []
    for keys, group in table.groupby(['family', 'seed', 'set', 'axis', 'variant'], sort=False):
        for subset in ['all'] + sorted(group.direction.unique()):
            sub = group if subset == 'all' else group[group.direction == subset]
            row = dict(zip(['family', 'seed', 'set', 'axis', 'variant'], keys))
            row.update(subset=subset, n=len(sub), patients=sub.patient_id.nunique(), new_validation_validity_flag=bool(sub.new_validation_validity_flag.iloc[0]))
            for metric in ['hit', 'gain', 'source_correct', 'other_stability']:
                if metric not in sub or sub[metric].isna().all():
                    continue
                stats = intervals(sub[metric].to_numpy(), sub.patient_id.to_numpy())
                if metric != 'gain':
                    stats.update(wilson(sub[metric].to_numpy()))
                row.update({f'{metric}_{k}': v for k, v in stats.items()})
            summary.append(row)
    pd.DataFrame(summary).to_csv(out / 'summary.csv', index=False)
    complete = stage == 'old' or all_b3
    json_write(out / 'complete.json', {'complete': complete, 'sets_or_variants': len(inputs), 'stage': stage, 'b1_b3_research_complete': all_b3, 'frozen_checkpoint_manifest_sha256': digest(base / 'frozen_checkpoints.json')})
    (out / 'README.md').write_text('Generated by scripts/v4_heldout/evaluate_heldout.py:regrade. per_slice.csv retains every family/seed and records source/target labels, hit/gain, source correctness, stability and frozen set metadata. summary.csv provides direction-specific slice/patient bootstrap intervals (10,000 resamples), with Wilson slice intervals for binary rates. Boundary-degenerate bootstrap intervals do not imply population certainty. complete.json distinguishes complete old-set grading from available-only B3 output grading if B1/B3 did not finish. Operating points and images are never reselected or regenerated; validity flags use new-cohort validation only and do not suppress results.\n')
    return {'complete': complete, 'sets': len(inputs), 'output': str(out)}
