"""Explicit recovery of the approved cohort after the recorded AWS failure.

Uses IDC's GCS mirror and sync for missing objects, preserving old receipts.
python -m scripts.v4_heldout.resume_download --plan-run preflight_20261016_01 --attempt-id recovery_01
"""
import argparse
import json
from datetime import datetime, timezone

import pandas as pd
import pydicom
from idc_index import IDCClient

from .audit import ROOT, sha
from .download import valid_id
from src.data.preprocess import normalize_field_strength, normalize_manufacturer


def main(plan_run, attempt_id):
    valid_id(plan_run)
    valid_id(attempt_id)
    base = ROOT / 'reports/v4_heldout_judge'
    prior = json.loads((base / f'download_{plan_run}' / 'result.json').read_text(encoding='utf-8'))
    assert not prior['complete'], 'Use the completed receipt, not recovery'
    plan_path = base / plan_run / 'download_plan.csv'
    assert sha(plan_path) == prior['plan_sha256']
    plan = pd.read_csv(plan_path)
    raw = ROOT / 'data/raw/duke_breast_cancer_mri_heldout' / plan_run
    assert str(raw) == prior['raw_folder'] and raw.is_dir()
    report = base / f'download_{plan_run}_{attempt_id}'
    report.mkdir(parents=True, exist_ok=False)
    before = {str(p): sha(p) for p in raw.rglob('*.dcm')}
    (report / 'preexisting_sha256.json').write_text(json.dumps(before, indent=2), encoding='utf-8')
    cap = prior['max_decimal_GB']
    receipt = {'plan_sha256': prior['plan_sha256'], 'raw_folder': str(raw), 'previous_failure_receipt': str(base / f'download_{plan_run}' / 'result.json'), 'max_decimal_GB': cap, 'source_bucket_location': 'gcs', 'started_utc': datetime.now(timezone.utc).isoformat(), 'complete': False}
    (report / 'request.json').write_text(json.dumps(receipt, indent=2), encoding='utf-8')
    client = IDCClient()
    headers = []
    try:
        existing_patients = {p.name for p in (raw / 'duke_breast_cancer_mri').iterdir() if p.is_dir()}
        assert existing_patients <= set(plan.PatientID)
        for i, row in plan.iterrows():
            if sum(p.stat().st_size for p in raw.rglob('*') if p.is_file()) > cap * 1e9:
                raise ValueError('Actual file bytes exceed approved cap; stop before next series')
            patient_dir = raw / 'duke_breast_cancer_mri' / row.PatientID
            files = list(patient_dir.rglob('*.dcm'))
            if len(files) < int(row.instanceCount):
                client.download_dicom_series(str(row.SeriesInstanceUID), str(raw), quiet=True, show_progress_bar=False, use_s5cmd_sync=True, source_bucket_location='gcs')
                files = list(patient_dir.rglob('*.dcm'))
            assert len(files) == int(row.instanceCount), f'{row.PatientID}: incomplete series'
            for file in files:
                ds = pydicom.dcmread(file, stop_before_pixels=True)
                mfg = normalize_manufacturer(getattr(ds, 'Manufacturer', ''))
                field = normalize_field_strength(getattr(ds, 'MagneticFieldStrength', None))
                assert str(ds.PatientID) == row.PatientID and str(ds.SeriesInstanceUID) == row.SeriesInstanceUID
                assert str(ds.SeriesDescription).strip().lower() == 'ax t1' and mfg == row.Manufacturer
                assert field == ('1.5T' if int(row.planning_field_strength_label) == 0 else '3.0T')
                headers.append({'patient_id': row.PatientID, 'series_uid': row.SeriesInstanceUID, 'sop_uid': str(ds.SOPInstanceUID), 'slice_path': str(file), 'judge_split': row.judge_split, 'manufacturer': mfg, 'field_strength': field, 'echo_time': float(getattr(ds, 'EchoTime', 'nan')), 'instance_number': int(getattr(ds, 'InstanceNumber', -1))})
            print(f'{i + 1}/64 patients downloaded and headers verified: {row.PatientID}', flush=True)
        frame = pd.DataFrame(headers)
        assert frame.sop_uid.is_unique
        frame.to_csv(report / 'verified_dicom_headers.csv', index=False)
        assert all(sha(p) == digest for p, digest in before.items()), 'Preexisting DICOM changed'
        receipt['complete'] = True
        receipt['instances_verified'] = len(frame)
        receipt['preexisting_files_unchanged'] = True
    except Exception as exc:
        receipt['error'] = repr(exc)
        if headers:
            pd.DataFrame(headers).to_csv(report / 'partial_verified_headers.csv', index=False)
        raise
    finally:
        receipt['bytes_on_disk'] = sum(p.stat().st_size for p in raw.rglob('*') if p.is_file())
        receipt['finished_utc'] = datetime.now(timezone.utc).isoformat()
        (report / 'result.json').write_text(json.dumps(receipt, indent=2), encoding='utf-8')
        (report / 'README.md').write_text('Generated by scripts/v4_heldout/resume_download.py. request.json references the failed original receipt and frozen approved plan. preexisting_sha256.json inventories prior DICOMs. result.json records success/failure, cap and preservation checks; verified_dicom_headers.csv (or partial_verified_headers.csv) records checked metadata. Uses the GCS mirror and sync for missing objects, with no new patient selection, and preserves earlier reports.\n', encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--plan-run', required=True)
    parser.add_argument('--attempt-id', required=True)
    args = parser.parse_args()
    main(args.plan_run, args.attempt_id)
