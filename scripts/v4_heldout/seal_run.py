"""Seal reviewed B2 code after local checks, without launching anything."""
import argparse
import json
import zipfile

from scripts.v4_convergence.core import digest, json_write
from scripts.v4_heldout.prepare_run import ROOT, valid_id
from scripts.v4_heldout.budget import CPU_RATE, GPU_RATE, TIMEOUT


def main(run_id):
    valid_id(run_id)
    base = ROOT / 'reports/v4_heldout_judge' / run_id
    checks = json.loads((base / 'local_tests.json').read_text())
    if not checks['passed']:
        raise ValueError('Fix local checks before sealing')
    sources = sorted((ROOT / 'scripts/v4_heldout').glob('*.py'))
    sources += [ROOT / 'scripts/v4_heldout/README.md', ROOT / 'scripts/v4_convergence/core.py', ROOT / 'scripts/v2_quickwins/judge_model.py', ROOT / 'src/models/predictor.py']
    manifest = [{'path': p.relative_to(ROOT).as_posix(), 'sha256': digest(p), 'bytes': p.stat().st_size} for p in sources]
    json_write(base / 'source_manifest.json', manifest)
    with zipfile.ZipFile(base / 'source_snapshot.zip', 'x', compression=zipfile.ZIP_DEFLATED) as archive:
        for path in sources:
            archive.write(path, path.relative_to(ROOT).as_posix())
    worst = 9 * (TIMEOUT + 30) * (GPU_RATE + CPU_RATE) + .25 + .05
    result = {'passed': True, 'local_checks': checks['tests_run'], 'gpu_jobs_launched': False, 'cloud_upload_done': False, 'controller_cap_proposed_usd': 4.75, 'total_cap_proposed_usd': 5.0, 'worker_upper_reservation_usd': (TIMEOUT + 30) * GPU_RATE, 'nine_worker_reservations_plus_controller_and_setup_usd': worst, 'source_snapshot_sha256': digest(base / 'source_snapshot.zip'), 'input_manifest_sha256': digest(base / 'input_manifest.json'), 'protocol_sha256': digest(base / 'protocol.json'), 'approval_still_required': True}
    json_write(base / 'preflight.json', result)
    (base / 'PREFLIGHT_README.md').write_text('''# Local B2 launch preflight

`local_tests.json` and local_tests.log were generated by scripts/v4_heldout/test_b2_pipeline.py. Checks include real-pack exclusion/integrity, complete synthetic CPU training/state reload, partial checkpoint preservation on a deadline, frozen-checkpoint guards, clustered uncertainty, budget reservations and the active-app guard. Synthetic checkpoints/metrics are retained only under tmp/, explicitly excluded from research results.

`preflight.json`, `source_manifest.json` and `source_snapshot.zip` are made by scripts/v4_heldout/seal_run.py after successful checks. They freeze the reviewed code and cost assumptions. `protocol.json`, input_manifest.json and inputs/ are generated by prepare_run.py. No GPU job or upload occurs during these steps. launch.py defaults to a read-only active-app/preflight check; --execute requires an approved extra allowance, and --wait queues locally until no Modal app is active. The computer must stay online until dispatch; once dispatched, the remote controller survives a local disconnect.

The proposed US$5 allowance is separate from B1/B3's US$15. Six 40-epoch training jobs plus three post-freeze evaluation workers share one A10, and each job reserves its full 900-second timeout plus startup and safety margin. Training preserves a partial checkpoint before timeout and stops without testing if incomplete. The controller also stops before launching a job whose reservation cannot fit. This is a conservative scheduling estimate; account-wide billing is external to this process. Rates were checked against https://modal.com/pricing on 2026-10-16.

No actual judge, original-test result, new re-grade or robustness success is claimed here. Queue/dispatch receipts (when present) record later explicit approval and launch rather than editing these preparation records.
''')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--run-id', required=True)
    main(parser.parse_args().run_id)
