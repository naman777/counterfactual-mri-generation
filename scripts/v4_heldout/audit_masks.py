"""Fetch only small official segmentation METADATA; never fetch mask images.

python -m scripts.v4_heldout.audit_masks --run-id mask_feasibility_20261016_01
"""
import argparse
import json
import re
from datetime import datetime, timezone

import idc_index_data
import pandas as pd
import requests

from .audit import ROOT, sha
from .download import valid_id


def main(run_id):
    valid_id(run_id)
    out = ROOT / 'reports/v4_downstream' / run_id
    out.mkdir(parents=True, exist_ok=False)
    base = 'https://www.cancerimagingarchive.net/wp-content/uploads/'
    names = ['duke_README.txt', 'segmentation_filepath_mapping.csv', 'BreastAndFGT_MRI_SEG_only_20220609.tcia']
    sources = []
    for name in names:
        with requests.get(base + name, timeout=30, stream=True) as response:
            response.raise_for_status()
            content = bytearray()
            for chunk in response.iter_content(65536):
                content.extend(chunk)
                if len(content) > 500_000:
                    raise ValueError('Metadata unexpectedly exceeds 500 kB; refusing larger payload')
        target = out / name
        with target.open('xb') as stream:
            stream.write(content)
        sources.append({'url': base + name, 'file': name, 'bytes': len(content), 'sha256': sha(target)})
    mapping = pd.read_csv(out / 'segmentation_filepath_mapping.csv')
    mapping['series_folder'] = mapping['Full Descriptive Path'].str.split('/').str[-2]
    mapping['mapped_series_description'] = mapping.series_folder.str.extract(r'^\d+(?:\.\d+)?-(.*)-\d+$')[0].str.strip().str.lower()
    assert mapping.mapped_series_description.notna().all()
    original = pd.concat([pd.read_csv(ROOT / f'data/processed/ax_t1_128/splits/{split}.csv').assign(original_split=split) for split in ['train', 'val', 'test']]).drop_duplicates('patient_id')
    mapping = mapping.merge(original[['patient_id', 'original_split', 'manufacturer_label', 'field_strength_label']], left_on='Patient ID', right_on='patient_id', how='left', validate='many_to_one')
    mapping['exact_ax_t1_description'] = mapping.mapped_series_description.eq('ax t1')
    mapping.to_csv(out / 'mapping_sequence_audit.csv', index=False)
    mapping.groupby('mapped_series_description').agg(patients=('Patient ID', 'nunique'), annotation_rows=('Patient ID', 'size')).reset_index().to_csv(out / 'mapped_sequence_counts.csv', index=False)
    mapping.dropna(subset=['original_split']).groupby(['original_split', 'manufacturer_label']).agg(patients=('Patient ID', 'nunique'), annotation_rows=('Patient ID', 'size')).reset_index().to_csv(out / 'original_cohort_patient_overlap.csv', index=False)
    uids = re.findall(r'^\d+(?:\.\d+)+$', (out / names[2]).read_text(encoding='utf-8'), re.MULTILINE)
    assert len(uids) == len(set(uids)) and len(uids) > 0
    catalog = pd.read_parquet(idc_index_data.IDC_INDEX_PARQUET_FILEPATH, filters=[('collection_id', '==', 'duke_breast_cancer_mri')])
    official = catalog[catalog.SeriesInstanceUID.isin(uids)].copy()
    assert len(official) == len(uids) and official.Modality.eq('SEG').all()
    official['in_original_cohort'] = official.PatientID.isin(original.patient_id)
    official.to_csv(out / 'official_2d_segmentation_catalog_matches.csv', index=False)
    summary = {'metadata_only': True, 'mask_images_downloaded': False, 'retrieved_utc': datetime.now(timezone.utc).isoformat(), 'sources': sources, 'mapping_patients': int(mapping['Patient ID'].nunique()), 'mapping_rows': len(mapping), 'mapping_original_patient_overlap': int(mapping.dropna(subset=['original_split'])['Patient ID'].nunique()), 'mapping_exact_ax_t1_rows': int(mapping.exact_ax_t1_description.sum()), 'official_2d_seg_series': len(official), 'official_2d_seg_catalog_MB': float(pd.to_numeric(official.series_size_MB).sum()), 'official_2d_seg_original_patient_overlap': int(official[official.in_original_cohort].PatientID.nunique()), 'direct_mask_transfer_established': False}
    (out / 'summary.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    (out / 'README.md').write_text('''# B5 tissue-mask feasibility follow-up

Generated by `python -m scripts.v4_heldout.audit_masks --run-id ''' + run_id + '''`. Only small public metadata files were retrieved. No mask images were downloaded or transferred to axial T1 slices.

The [official TCIA collection](https://www.cancerimagingarchive.net/collection/duke-breast-cancer-mri/) lists breast/FGT supplements. Its 2D SEG manifest resolves the generic `Segmentation` entries in the cached IDC catalogue; these are distinguishable from BAMF tumour AI labels. The 3D supplement's README describes manual tissue annotations on fat-saturated pre-contrast gradient-echo acquisitions. The 2D filepath mapping names dynamic/pre-contrast series; our sequence audit finds no exact `ax t1` mapping. Patient overlap alone therefore does not establish aligned masks on this project's images. TCIA also cautions that deidentified frame-of-reference identifiers are unreliable for alignment.

`duke_README.txt`, `segmentation_filepath_mapping.csv` and `BreastAndFGT_MRI_SEG_only_20220609.tcia` are unchanged source metadata. `summary.json` records source URLs, retrieval time, hashes, overlaps and catalogue size. `mapping_sequence_audit.csv` joins mapped series names and original patient splits; `mapped_sequence_counts.csv` summarises them. `original_cohort_patient_overlap.csv` reports patient overlap by split/vendor, not labelled axial-T1 slices. `official_2d_segmentation_catalog_matches.csv` links the official SEG manifest to cached catalogue entries. Every output is made by `audit_masks.py`.

Next: inspect referenced SOP/series IDs, image geometry and segment definitions in a small explicitly approved mask sample; verify registration and tissue labels visually. Do not apply dynamic-sequence masks to axial T1 by resizing or patient ID, or treat tumour boxes as tissue ground truth. A full B5 segmentation experiment remains pending this compatibility check and the final B1/B3 generator. The receptor-label alternative also requires a defensible training-only endpoint choice and adequate patient support.
''', encoding='utf-8')
    print(json.dumps({k: v for k, v in summary.items() if k != 'sources'}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--run-id', required=True)
    main(parser.parse_args().run_id)
