"""Build 20 illustrative saved cases on CPU: python -m api.build_demo.

No denoising is allowed. Existing B3 float arrays and CPU classifiers supply every
result. Selection covers all test patients, then balances source acquisitions and
includes judge disagreement. This is an illustrative selection, never an estimate.
"""
import json
from unittest.mock import patch

from api import data, demo_cache
from api.main import EditRequest, run_edit


def build():
    output = demo_cache.CACHE_DIR
    output.mkdir(parents=True, exist_ok=True)
    if (output / "manifest.json").exists():
        raise FileExistsError("Demo bundle already exists; preserve it and choose a new output folder for a rebuild")
    rows = data.evidence_rows("main_field_strength_t100_w5_s0")
    # Explicit, reviewable ordering: each patient first, with differing verdicts.
    selected = []
    for patient in sorted({r["slice"]["patient"] for r in rows}):
        candidates = [r for r in rows if r["slice"]["patient"] == patient]
        desired = len(selected) % 4
        selected.append(min(candidates, key=lambda r: (abs(r["confirmed"] - desired), r["index"])))
    for mfg in (0, 1):
        for fs in (0, 1):
            candidates = [r for r in rows if r not in selected and r["slice"]["manufacturer"] == mfg and r["slice"]["field_strength"] == fs]
            if candidates:
                selected.append(min(candidates, key=lambda r: (r["confirmed"], r["index"])))
    for row in rows:
        if len(selected) >= 20:
            break
        if row not in selected:
            selected.append(row)
    selected = selected[:20]
    manifest = dict(schema=1, selection="All 16 patients, source acquisition cells and differing judge outcomes. Illustrative cases, not a representative estimate.",
                    slices=[dict(id=r["slice"]["id"], patient=r["slice"]["patient"], confirmed=r["confirmed"],
                                 manufacturer=r["slice"]["manufacturer"], field_strength=r["slice"]["field_strength"],
                                 paper_seeds=r["slice"]["paper_seeds"]) for r in selected], results={}, result_ids={})
    with patch("api.main.editor", side_effect=AssertionError("Demo build must never denoise")), patch("api.main.sample", side_effect=AssertionError("Demo build must never denoise")):
        for row in selected:
            source = row["slice"]
            for axis, t, w in (("fs", 100, 5.), ("mfg", 300, 3.)):
                for null in (False, True):
                    req = EditRequest(slice_id=source["id"], manufacturer=1-source["manufacturer"] if axis == "mfg" else source["manufacturer"],
                                      field_strength=1-source["field_strength"] if axis == "fs" else source["field_strength"],
                                      timestep=t, guidance=w, seed=source["paper_seeds"][axis], null_edit=null)
                    result = run_edit(req)
                    if not result["cached"]:
                        raise AssertionError("Expected saved B3 evidence")
                    key = demo_cache.request_key(req)
                    filename = key + ".json"
                    (output / filename).write_text(json.dumps(result, allow_nan=False), encoding="utf-8")
                    manifest["results"][key] = filename
                    manifest["result_ids"][result["id"]] = filename
            print(f"Saved {source['id']} ({len(manifest['results'])} results)", flush=True)
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    (output / "README.md").write_text("# Saved demo evidence\n\nGenerated by `python -m api.build_demo`. The manifest lists the 20 selected slices and exact requests.\nEach JSON contains images, foreground histogram, CPU judge probabilities, metrics and B3 provenance.\nBoth axis presets and same-noise null edits are saved (80 results). No new diffusion sampling.\nSelection is illustrative and includes disagreement. Cohort estimates come from Results.\nCopy this directory with the app for replay. No GPU or model loading is used for these requests.\n", encoding="utf-8")
    demo_cache.manifest.cache_clear()


if __name__ == "__main__":
    build()
